    private static readonly Dictionary<string, StringencyDef> ByKey = Defs.ToDictionary(d => d.Key);

    public static Dictionary<string, bool> Defaults() => Defs.ToDictionary(d => d.Key, d => d.Default);

    /// <summary>Any unknown key in `raw` is dropped; any missing known key falls back to its default - adding a switch never requires a data migration.</summary>
    public static Dictionary<string, bool> Normalize(Dictionary<string, bool>? raw)
    {
        var result = Defaults();
        if (raw != null)
        {
            foreach (var key in result.Keys.ToList())
            {
                if (raw.TryGetValue(key, out var v)) result[key] = v;
            }
        }
        return result;
    }

    public static bool On(Dictionary<string, bool>? list, string key)
    {
        if (!ByKey.TryGetValue(key, out var def)) return false;
        if (list != null && list.TryGetValue(key, out var v)) return v;
        return def.Default;
    }

    public static StringencyDef? Def(string key) => ByKey.GetValueOrDefault(key);
