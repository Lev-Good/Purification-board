    public static HalachaTopic? GetTopic(string id) =>
        Topics.FirstOrDefault(t => string.Equals(t.Id, id, StringComparison.OrdinalIgnoreCase));

    public static IEnumerable<HalachaTopic> GetByCategory(string category) =>
        Topics.Where(t => string.Equals(t.Category, category, StringComparison.OrdinalIgnoreCase));

    public static IEnumerable<HalachaTopic> Search(string query)
    {
        if (string.IsNullOrWhiteSpace(query)) return Topics;
        var q = query.Trim();
        return Topics.Where(t =>
            t.Title.Contains(q, StringComparison.OrdinalIgnoreCase) ||
            t.Summary.Contains(q, StringComparison.OrdinalIgnoreCase) ||
            t.Category.Contains(q, StringComparison.OrdinalIgnoreCase) ||
            t.Body.Any(b => b.Contains(q, StringComparison.OrdinalIgnoreCase)) ||
            t.Points.Any(p => p.Contains(q, StringComparison.OrdinalIgnoreCase)));
    }
