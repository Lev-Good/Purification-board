const BY_KEY = STRINGENCY_DEFS.reduce((acc, def) => {
    acc[def.key] = def;
    return acc;
}, {});

/** ברירות המחדל של המתגים. */
export function defaultStringencies() {
    return STRINGENCY_DEFS.reduce((acc, def) => {
        acc[def.key] = def['default'];
        return acc;
    }, {});
}

/**
 * מנרמל מתגים שנקראו מן ה-שמירה: כל מתג שאינו מוכר מדולג, וכל מתג חסר מקבל את
 * ברירת המחדל שלו. כך הוספת מתג אינה דורשת הגירת נתונים.
 */
export function normalizeStringencies(raw) {
    const base = defaultStringencies();
    if (!raw || typeof raw !== 'object') return base;
    Object.keys(base).forEach(key => {
        if (typeof raw[key] === 'boolean') base[key] = raw[key];
    });
    return base;
}

/** האם מתג מסוים דלוק בתוך רשימת המתגים. */
export function stringencyOn(list, key) {
    const def = BY_KEY[key];
    if (!def) return false;
    const value = list && typeof list[key] === 'boolean' ? list[key] : def['default'];
    return value === true;
}

/** ההגדרה של מתג, לתצוגה במסך ההגדרות. */
export function stringencyDef(key) {
    return BY_KEY[key] || null;
}

/**
 * פרופיל מנהג (אשכנז/עדות מזרח) — שכבה נוחה מעל כמה מתגים, לא מנגנון נפרד.
 * בחירת פרופיל רק **מגדירה** את הצירוף; שינוי מתג בודד לאחר מכן "מוציא" את
 * המצב מן הפרופיל, ואינו נעול. `orZarua` הוא מפתח מיוחד: הוא נשמר בנפרד
 * מ-STRINGENCY_DEFS (ב-`js/storage.js`, לא ב-`taharahStringencies`), אבל
 * הוא חלק לוגי מהפרופיל. `sepharad` הוא מפתח פנימי בלבד — בממשק המשתמשת
 * הפרופיל הזה מוצג כ"עדות מזרח".
 *
 * מקור: מסמכי "יסודות הבית" (מקור משני). אור זרוע ואור זרוע בל"א מאומתים גם
 * בספר הראשי; כרתי ופלתי מובא רק מהמקור המשני — ראו מקור המתג עצמו.
 */
export const MINHAG_PROFILES = {
    ashkenaz: { orZarua: true, orZaruaDay31: true, karetiUfaletei: true },
    sepharad: { orZarua: false, orZaruaDay31: false, karetiUfaletei: false }
};

/**
 * מזהה את הפרופיל לפי מצב שלושת המתגים בפועל, או `'custom'` כשאין התאמה מלאה
 * לאף פרופיל. פונקציה טהורה: `state` מגיע כבר קרוא מן האחסון (ראו js/app.js).
 */
export function detectMinhagProfile(state) {
    const s = state || {};
    for (const [name, profile] of Object.entries(MINHAG_PROFILES)) {
        if (Object.keys(profile).every(key => s[key] === profile[key])) return name;
    }
    return 'custom';
}
