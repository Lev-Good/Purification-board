const BY_CODE = DAY_MARKS.reduce((acc, m) => {
    acc[m.code] = m;
    return acc;
}, {});

/** האם הקוד הוא סימון יום מוכר. */
export function isDayMark(code) {
    return !!BY_CODE[code];
}

/** התווית של סימון, לתצוגה. */
export function dayMarkLabel(code) {
    return BY_CODE[code] ? BY_CODE[code].label : String(code);
}

/** הסימונים של רשומת יום, מנורמלים (קודים מוכרים בלבד, בלא כפילויות). */
export function marksOf(entry) {
    if (!entry || !Array.isArray(entry.marks)) return [];
    const out = [];
    entry.marks.forEach(code => {
        if (typeof code === 'string' && BY_CODE[code] && out.indexOf(code) === -1) out.push(code);
    });
    return out;
}

/** האם רשומת היום נושאת סימון מסוים. */
export function hasMark(entry, code) {
    return marksOf(entry).indexOf(code) !== -1;
}

/**
 * כל הסימונים ב-db, לפי יום: `Map<abs, string[]>`.
 * @param {Object} db
 */
export function marksByDay(db) {
    const map = new Map();
    Object.keys(db || {}).map(Number).forEach(abs => {
        const marks = marksOf(db[abs]);
        if (marks.length) map.set(abs, marks);
    });
    return map;
}

/**
 * ימי הכתם ב-db — `Set` של ימים שסומנו בהם "מצאתי כתם".
 *
 * המנוע צריך אותם פעמיים: כדי לשלול קיבוע וסת מחמתם, וכדי לבחון את דעת
 * שערי טוהר (מתג `stainUproots`, `js/stringencies.js`) `[שט ל"ה | עמ' 127–128]`.
 * @param {Map<number, string[]>} marks
 */
export function stainDays(marks) {
    const out = new Set();
    (marks || new Map()).forEach((list, abs) => {
        if (list.indexOf('stain') !== -1) out.add(abs);
    });
    return out;
}

/**
 * הפטור של עונת אור זרוע שחל עליה.
 *
 * כללי הספר `[שט כ"ז | עמ' 49]`:
 *  - **ליל טבילה** — "מותרת, ותבדוק קו\"ת": הפטור חל כשהעונה שנדרשת לאור זרוע היא
 *    **ליל הטבילה**. לכן `tevilot` מכיל את **היום שהלילה שלו הוא ליל הטבילה**.
 *  - **ליל החופה / בעילת מצוה** — "מותר": סימון `chuppah` על אותו יום.
 *  - **יוצא לדרך** — "יש להקל": סימון `travel` על אותו יום (היום שיצא לדרך).
 *  - **ליל שבת — אין להקל**, וכן **העונה שלפני יום הל' חייבת** אף בעונת אור זרוע:
 *    ולכן אין כאן פטור — ואין לסמן "ליל שבת" כלילה פטור.
 *
 * @param {Object} params
 * @param {number} params.shiftAbs - היום שאליו נוספה עונת אור זרוע
 * @param {string} params.shiftOna - 'night' | 'day'
 * @param {Map<number, string[]>} params.marks - סימוני הימים
 * @param {Set<number>} params.tevilot - הימים שלילוֹתיהם הן ליל טבילה
 * @returns {{code: string, label: string, reason: string, source: string}|null}
 */
export function orZaruaExemptionFor({ shiftAbs, shiftOna, marks, tevilot }) {
    const dayMarks = (marks && marks.get(shiftAbs)) || [];

    if (shiftOna === 'night' && tevilot && tevilot.has(shiftAbs)) {
        return {
            code: 'lilTvila',
            label: 'ליל טבילה',
            reason: 'פטור מעונת אור זרוע — ליל טבילה ("מותרת, ותבדוק קו\"ת")',
            source: '[שט כ"ז | עמ\' 49]'
        };
    }
    if (shiftOna === 'night' && dayMarks.indexOf('chuppah') !== -1) {
        return {
            code: 'chuppah',
            label: 'ליל החופה / בעילת מצוה',
            reason: 'פטור מעונת אור זרוע — ליל החופה / בעילת מצוה ("מותר")',
            source: '[שט כ"ז | עמ\' 49]'
        };
    }
    if (dayMarks.indexOf('travel') !== -1) {
        return {
            code: 'travel',
            label: 'יציאה לדרך / בא מן הדרך',
            reason: 'פטור מעונת אור זרוע — יוצא לדרך, והוא הדין בבא מן הדרך '
                + '("אף שבעונת הוסת מחמירים לאסור בתשמיש, בעונת האור זרוע יש להקל")',
            source: '[שט כ"ז | עמ\' 49] · [שט כ"ח | עמ\' 57]'
        };
    }
    return null;
}

